// Bundles the plugin host into todo/plugin_host.mjs, one file with the QuickJS
// wasm inlined, so the CLI can run plugins with nothing but Node; and the
// code-plugin worker into lib/plugins/code-worker.bundle.mjs, which the server's
// bundler ships as a single asset. First it regenerates
// lib/plugins/shipped/sources.ts from the shipped plugin files, so they reach
// every bundler as plain strings, after bundling each code plugin written in
// shipped/src into the single module a plugin must be.
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const shipped = path.join(root, "lib/plugins/shipped");
const outfile = path.resolve(root, "../todo/plugin_host.mjs");

export function shippedSources() {
  const files = readdirSync(shipped).filter((f) => /\.(yaml|m?js)$/.test(f)).sort();
  const entries = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(path.join(shipped, f), "utf8"))},`);
  return `// Generated by scripts/build-plugin-host.mjs from the files beside it; edit those and rebuild.\n`
    + `export const SOURCES: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
}

/** esbuild options for each shipped code plugin with a source in shipped/src. */
export function shippedCodeBuilds() {
  const src = path.join(shipped, "src");
  return readdirSync(src).filter((f) => f.endsWith(".ts")).sort().map((f) => ({
    entryPoints: [path.join(src, f)],
    outfile: path.join(shipped, f.replace(/\.ts$/, ".js")),
    bundle: true, platform: "neutral", format: "esm", target: "es2020", legalComments: "none",
    banner: { js: `// Generated by scripts/build-plugin-host.mjs from src/${f}; edit that and rebuild.` },
  }));
}

const BANNER = "import { createRequire as __createRequire } from 'node:module'; const require = __createRequire(import.meta.url);";

/** esbuild options for the worker bundle; `write: false` gives its text, for checking it's current. */
export const workerBuild = {
  entryPoints: [path.join(root, "lib/plugins/code-worker.mjs")],
  outfile: path.join(root, "lib/plugins/code-worker.bundle.mjs"),
  bundle: true, platform: "node", format: "esm", target: "node20", minify: true, legalComments: "none",
  banner: { js: `// Generated by scripts/build-plugin-host.mjs from code-worker.mjs; edit that and rebuild.\n${BANNER}` },
};

if (process.argv[1] === import.meta.filename) {
  await build({ ...workerBuild, logLevel: "info" });
  for (const opts of shippedCodeBuilds()) await build({ ...opts, logLevel: "info" });
  writeFileSync(path.join(shipped, "sources.ts"), shippedSources());
  await build({
    entryPoints: [path.join(root, "lib/plugins/cli-entry.ts")],
    outfile,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    minify: true,
    legalComments: "none",
    // Bundled CommonJS dependencies still call require for Node built-ins.
    banner: { js: BANNER },
    logLevel: "info",
  });
}
